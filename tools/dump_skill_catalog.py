"""Dump every skill tree used by the current roster into design/skill_catalog.json (merging).

Runs against the live game through the UEBridge mod (ue4ss/bridge/request.json -> response.json),
so the game must be running with a save loaded. Trees are keyed by asset name and MERGED: run it on
different saves (or after recruiting new classes) to fill in trees this save doesn't have.

Each node carries `starting`: true for the free nodes the vanilla game unlocks on its own
(IsStartNode or IsAlwaysUnlocked -- e.g. every class's start passive, Jackbot's StackingBuff +
JackCloak). That is the marker for the planned YAML option "include starting skills in item pool":
off (default) = starting skills are free and never AP items; on = they become AP items like any
other node (the vanilla tree still shows them unlocked either way).

Usage (from the repo root, game running):  python tools/dump_skill_catalog.py
"""
import json, os, sys, time, uuid

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BRIDGE = os.path.join(ROOT, "ue4ss", "bridge")
OUT = os.path.join(ROOT, "design", "skill_catalog.json")

LUA = r'''
local trees, order = {}, {}
local function fn(o) return o:GetFName():ToString() end
for _, r in ipairs(FindAllOf("GanderCharacterRoster") or {}) do
  if r:IsValid() and r:GetFullName():find("/Engine/Transient",1,true) then
    local a = r.SoldierRoster
    for i = 1, #a do
      local cd = a[i]
      local tname = fn(cd.AbilityTreeType)
      local t = trees[tname]
      if not t then
        t = { tree = tname, class = tname:match("^AttributeTree_(%a+)") or "?", gears = {}, nodes = {} }
        trees[tname] = t; order[#order+1] = tname
        local ab = cd.AbilityTree.Abilities
        for j = 1, #ab do
          local it = ab[j]
          local c, p = it.AbilityCard, it.Passive
          local kind, asset
          if c and c:IsValid() then kind, asset = "active", fn(c)
          elseif p and p:IsValid() then kind, asset = "passive", fn(p) end
          if kind then
            t.nodes[#t.nodes+1] = string.format('{"index":%d,"asset":"%s","kind":"%s","start_node":%s,"always_unlocked":%s,"x":%d,"y":%d}',
              j-1, asset, kind, tostring(it.IsStartNode == true), tostring(it.IsAlwaysUnlocked == true),
              it.LocationXIndex or 0, it.LocationYIndex or 0)
          end
        end
      end
      t.gears[#t.gears+1] = '"' .. cd.FullName:ToString():gsub('"', '\\"') .. '"'
    end
  end
end
local parts = {}
for _, k in ipairs(order) do
  local t = trees[k]
  parts[#parts+1] = string.format('{"tree":"%s","class":"%s","gears":[%s],"nodes":[%s]}', t.tree, t.class, table.concat(t.gears, ","), table.concat(t.nodes, ","))
end
return "[" .. table.concat(parts, ",") .. "]"
'''

def bridge_eval(code, timeout=60):
    rid = uuid.uuid4().hex[:8]
    tmp = os.path.join(BRIDGE, "request.json.tmp")
    with open(tmp, "w") as f:
        json.dump({"id": rid, "op": "eval", "code": code}, f)
    os.replace(tmp, os.path.join(BRIDGE, "request.json"))
    t0 = time.time()
    while time.time() - t0 < timeout:
        try:
            r = json.load(open(os.path.join(BRIDGE, "response.json")))
            if r.get("id") == rid:
                if not r.get("ok"):
                    sys.exit("bridge error: %s" % r.get("error"))
                return r.get("result")
        except (OSError, ValueError):
            pass
        time.sleep(0.2)
    sys.exit("bridge timeout -- is the game running with UEBridge loaded?")

def main():
    trees = json.loads(bridge_eval(LUA))
    cat = {"note": ("Generated by tools/dump_skill_catalog.py from the live game (merged across saves). "
                    "'starting' = free in vanilla (IsStartNode or IsAlwaysUnlocked): the marker for the "
                    "'include starting skills in item pool' YAML option."),
           "trees": {}}
    if os.path.exists(OUT):
        cat = json.load(open(OUT))
    for t in trees:
        for n in t["nodes"]:
            n["starting"] = bool(n["start_node"] or n["always_unlocked"])
        prev = cat["trees"].get(t["tree"], {})
        gears = sorted(set(prev.get("gears", [])) | set(t["gears"]))
        cat["trees"][t["tree"]] = {"class": t["class"], "gears_seen": gears, "nodes": t["nodes"]}
    # per-class convenience view: every starting skill by class
    starting = {}
    for name, t in cat["trees"].items():
        for n in t["nodes"]:
            if n["starting"]:
                starting.setdefault(t["class"], {})[n["asset"]] = n["kind"]
    cat["starting_skills_by_class"] = {c: [{"asset": a, "kind": k} for a, k in sorted(v.items())]
                                       for c, v in sorted(starting.items())}
    cat["trees"] = dict(sorted(cat["trees"].items()))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        json.dump(cat, f, indent=1)
    print("wrote %s: %d tree(s)" % (OUT, len(cat["trees"])))
    for name, t in cat["trees"].items():
        print("  %-32s %-9s %2d nodes, starting: %s" % (name, t["class"], len(t["nodes"]),
              ", ".join(n["asset"] for n in t["nodes"] if n["starting"])))

if __name__ == "__main__":
    main()
